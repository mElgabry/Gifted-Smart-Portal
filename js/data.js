const SessionManager = {
  _memSession: null,
  saveSession(authData, remember) {
    const dataToSave = JSON.stringify(authData);
    this._memSession = dataToSave;
    try {
      if (remember) {
        localStorage.setItem('moe_gifted_auth', dataToSave);
        sessionStorage.removeItem('moe_gifted_auth');
      } else {
        sessionStorage.setItem('moe_gifted_auth', dataToSave);
        localStorage.removeItem('moe_gifted_auth');
      }
    } catch (e) {
      // Fallback to in-memory session in restricted sandboxes
    }
  },

  getSession() {
    let s = this._memSession;
    try {
      s = sessionStorage.getItem('moe_gifted_auth') || localStorage.getItem('moe_gifted_auth') || s;
    } catch (e) {
      // Use in-memory fallback
    }
    if (!s) return null;
    try {
      const parsed = JSON.parse(s);
      if (parsed.expiresAt && Date.now() > parsed.expiresAt) {
        this.clearSession();
        return null;
      }
      return parsed;
    } catch (e) {
      return null;
    }
  },

  clearSession() {
    this._memSession = null;
    try {
      sessionStorage.removeItem('moe_gifted_auth');
      localStorage.removeItem('moe_gifted_auth');
    } catch (e) {
      // Ignore storage errors in sandbox
    }
  }
};



// Setup Transparent Window.Fetch Interceptor for /api/v1/auth/* endpoints
const _nativeFetch = window.fetch;
window.fetch = async function(input, init) {
  const url = typeof input === 'string' ? input : (input ? input.url : '');
  if (url && url.includes('/api/v1/auth/login')) {
    try {
      const body = init && init.body ? JSON.parse(init.body) : {};
      const result = await AuthServer.handleServerLogin(body.username, body.password);
      return new Response(JSON.stringify(result), {
        status: 200,
        headers: { 'Content-Type': 'application/json' }
      });
    } catch (err) {
      return new Response(JSON.stringify({ status: 'error', code: 401, message: err.message }), {
        status: 401,
        headers: { 'Content-Type': 'application/json' }
      });
    }
  } else if (url && url.includes('/api/v1/auth/verify-2fa')) {
    try {
      const body = init && init.body ? JSON.parse(init.body) : {};
      const result = await AuthServer.verify2FA(body.otp, body.userId);
      return new Response(JSON.stringify(result), {
        status: 200,
        headers: { 'Content-Type': 'application/json' }
      });
    } catch (err) {
      return new Response(JSON.stringify({ status: 'error', code: 400, message: err.message }), {
        status: 400,
        headers: { 'Content-Type': 'application/json' }
      });
    }
  } else if (url && url.includes('/api/v1/auth/change-password')) {
    try {
      const body = init && init.body ? JSON.parse(init.body) : {};
      const result = await AuthServer.handleServerChangePassword(body.userId, body.currentPassword, body.newPassword);
      return new Response(JSON.stringify(result), {
        status: 200,
        headers: { 'Content-Type': 'application/json' }
      });
    } catch (err) {
      return new Response(JSON.stringify({ status: 'error', code: 400, message: err.message }), {
        status: 400,
        headers: { 'Content-Type': 'application/json' }
      });
    }
  } else if (url && url.includes('/api/v1/auth/reset-password')) {
    try {
      const body = init && init.body ? JSON.parse(init.body) : {};
      const result = await AuthServer.handleServerResetPassword(body.actorUserId, body.targetUserId);
      return new Response(JSON.stringify(result), {
        status: 200,
        headers: { 'Content-Type': 'application/json' }
      });
    } catch (err) {
      return new Response(JSON.stringify({ status: 'error', code: 403, message: err.message }), {
        status: 403,
        headers: { 'Content-Type': 'application/json' }
      });
    }
  } else if (url && url.includes('/api/v1/auth/logout')) {
    return new Response(JSON.stringify({ status: 'success', code: 200, message: 'تم إنهاء الجلسة بنجاح' }), {
      status: 200,
      headers: { 'Content-Type': 'application/json' }
    });
  }
  return _nativeFetch.apply(this, arguments);
};

